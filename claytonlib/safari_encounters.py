"""In-house HGSS Safari-Zone encounter resolution (replaces the Pokefinder handoff).

Given the loaded Seed A and the current Safari-Zone block configuration, this computes
*which pokemon* an encounter yields at each advance frame -- so Section A.2 can pick a Metang
frame itself instead of round-tripping through Pokefinder (clayton-ctd.8).

Five encounter **methods** are supported (clayton-858): ``grass`` and ``surf`` (both triggered
by Sweet Scent, on land and while surfing) and ``old_rod``/``good_rod``/``super_rod``.  Surf
and the rods exist only in the five areas with water -- Meadow, Rocky Beach, Wetland, Swamp
and Marshland (``has_water``); asking for a water method anywhere else raises.

How it works (grass verified against notes/pokefinder_spread.md, 132/132 rows; the
surf/rod extensions derive from the same PokeFinder source -- see notes/safari_water.md):

  * **Species is one RNG draw, for every method.** HGSS Safari uses a special Method-K branch:
    the encounter slot is a flat ``(rand >> 16) % 10`` (10 equally-likely slots) whether you
    are in grass, surfing, or fishing -- the normal 100-value threshold tables never apply
    here, and neither does a level draw (``calculateLevel<false, ...>`` just reads the slot's
    level).  We never need the PID/IV draws to know the species, so no shiny logic.
  * **Frame -> slot:** ``slot(frame) = (advance_rng^(frame+draws)(seedA) >> 16) % 10``, where
    ``draws`` is 1 for grass and surf and **2 for a rod**.  (The encounter consumes one advance
    past the frame you act on; the +1 offset was fit to ground truth.  A rod spends that first
    advance on the nibble check below, pushing the slot draw one further.)
  * **A rod first rolls whether anything bites at all:** ``(rand >> 16) % 100 < rate``, with
    ``rate`` = 25/50/75 for old/good/super rod, plus the lead's happiness bonus, doubled by a
    Suction Cups lead.  A failed check is "Not even a nibble..." -- no encounter, and the
    stream is left exactly one advance further on.
  * **Blocks shape the table.** Each area/method has a default 10-slot table (per time of day)
    plus block-conditional entries; each satisfied conditional replaces the next slot from the
    top, in order (PokeFinder ``Encounters4::getHGSSSafari``).  The number of conditionals
    differs by method -- grass 10, surf 3, each rod 2 -- but the resolved table is always 10
    slots.  Block scores are the day-multiplier-applied values (as Pokefinder takes them), one
    per type: plains/forest/peak/water.

Data: ``claytonlib/basedata/safari_zones.json`` (all 12 areas, all 5 methods), generated by
``one-offs/extract_safari_zones.py`` from PokeFinder's raw encounter NARC.
"""
from functools import lru_cache

from claytonlib._resources import basedata_json
from claytonlib.safari import advance_rng
from claytonlib.species_names import canonical_species_name

# Block-type -> index in the score vector.  Index 0 is the game's "no condition" sentinel (a
# conditional's second slot is often (type=0, quantity=0), i.e. always satisfied), so the four real
# categories are 1..4.  Confirmed against ground truth: Metang's Mountain condition is (peak, 56).
BLOCK_TYPES = {"none": 0, "plains": 1, "forest": 2, "peak": 3, "water": 4}
_TOD = {"morning": 0, "day": 1, "night": 2}

#: The encounter methods, in the order the game's own data stores them.
METHODS = ("grass", "surf", "old_rod", "good_rod", "super_rod")
#: Methods that need water, and so exist only in the five areas with any.
WATER_METHODS = ("surf", "old_rod", "good_rod", "super_rod")
#: Methods that cast a line, and therefore roll the nibble check before the slot.
ROD_METHODS = ("old_rod", "good_rod", "super_rod")
#: Base hook rate per rod, out of 100 (PokeFinder getHGSSSafari's per-rod `rate` argument).
ROD_BASE_RATE = {"old_rod": 25, "good_rod": 50, "super_rod": 75}
#: The lead-happiness bonuses the game applies to a rod's hook rate, as Pokefinder offers them.
#: Pass the one matching your lead; 0 is the safe default (it under-predicts hooks rather than
#: promising ones that don't happen).
HAPPINESS_BONUSES = (0, 20, 30, 40, 50)
#: How many advances into the encounter the slot draw sits, per method (see the module docstring).
_SLOT_DRAW = {"grass": 1, "surf": 1, "old_rod": 2, "good_rod": 2, "super_rod": 2}

# Spellings a caller might reasonably use for each method -- the UI, the notebooks and
# PokeFinder itself all name these slightly differently.
_METHOD_ALIASES = {
    "grass": "grass", "land": "grass", "tall grass": "grass", "tall_grass": "grass",
    "surf": "surf", "surfing": "surf", "water": "surf",
    "old_rod": "old_rod", "old rod": "old_rod", "oldrod": "old_rod", "old": "old_rod",
    "good_rod": "good_rod", "good rod": "good_rod", "goodrod": "good_rod", "good": "good_rod",
    "super_rod": "super_rod", "super rod": "super_rod", "superrod": "super_rod",
    "super": "super_rod",
}
#: Human-readable method labels, for error messages and UI lists.
METHOD_LABELS = {"grass": "Grass (Sweet Scent)", "surf": "Surfing (Sweet Scent)",
                 "old_rod": "Old Rod", "good_rod": "Good Rod", "super_rod": "Super Rod"}
#: What the player physically does on the target frame, per method -- the verb a route guide
#: needs ("Sweet Scent there" vs "cast the Super Rod there").
METHOD_ACTIONS = {"grass": "Sweet Scent", "surf": "Sweet Scent",
                  "old_rod": "cast the Old Rod", "good_rod": "cast the Good Rod",
                  "super_rod": "cast the Super Rod"}

# In-game clock boundaries for the three time-of-day buckets (user-provided, clayton-b42.7.1):
# morning 4:00-9:59, day 10:00-19:59, night 20:00-3:59 (wraps past midnight). These three
# windows tile the full 24 hours with no gaps -- every real-clock hour falls in exactly one.


def time_of_day(when) -> str:
    """The time-of-day bucket ("morning"/"day"/"night") for a real clock hour.

    `when` is a datetime, or a plain hour (0-23) int. Right now every bucket is treated as
    equally valid by default -- using block-table data to determine which buckets actually
    carry (or alter the odds of) a given species is deliberately deferred future work, not
    implemented here (clayton-b42.7.1); this just classifies a clock time, nothing more.
    """
    hour = when.hour if hasattr(when, "hour") else int(when)
    if 4 <= hour < 10:
        return "morning"
    if 10 <= hour < 20:
        return "day"
    return "night"

@lru_cache(maxsize=1)
def _zones() -> dict:
    return basedata_json("safari_zones.json")


@lru_cache(maxsize=1)
def _areas_by_lower() -> dict:
    return {k.lower(): k for k in _zones() if not k.startswith("_")}


def safari_areas() -> list[str]:
    """The Safari-Zone area names that have encounter data (canonical spelling)."""
    return [k for k in _zones() if not k.startswith("_")]


def _area_key(area: str) -> str:
    key = _areas_by_lower().get(str(area).lower())
    if key is None:
        raise ValueError(f"unknown safari area {area!r}; known: {safari_areas()}")
    return key


def normalize_method(method) -> str:
    """The canonical method name for a user-supplied spelling (see ``_METHOD_ALIASES``)."""
    key = str(method).strip().lower().replace("-", "_")
    canon = _METHOD_ALIASES.get(key) or _METHOD_ALIASES.get(key.replace("_", " "))
    if canon is None:
        raise ValueError(f"unknown encounter method {method!r}; use one of {list(METHODS)}")
    return canon


def has_water(area: str) -> bool:
    """Whether `area` has any water -- i.e. whether surf and the rods work there at all."""
    return bool(_zones()[_area_key(area)]["has_water"])


def safari_methods(area: str) -> list[str]:
    """The encounter methods available in `area` (grass everywhere; the four water methods
    only in the five areas with water), in ``METHODS`` order."""
    entry = _zones()[_area_key(area)]
    return [m for m in METHODS if m in entry]


def _method_table(area: str, method: str) -> dict:
    """The resolved area entry's sub-table for `method`, with a specific error if it has none."""
    key = _area_key(area)
    entry = _zones()[key]
    if method not in entry:
        raise ValueError(
            f"{METHOD_LABELS[method]} encounters don't exist in {key} — it has no water. "
            f"Water areas: {', '.join(a for a in safari_areas() if has_water(a))}.")
    return entry[method]


def _tod_name(tod) -> str:
    if isinstance(tod, int):
        for name, idx in _TOD.items():
            if idx == tod:
                return name
        raise ValueError(f"time-of-day index out of range: {tod}")
    key = str(tod).lower()
    if key not in _TOD:
        raise ValueError(f"unknown time-of-day {tod!r}; use one of {list(_TOD)}")
    return key


def _block_vector(blocks) -> list[int]:
    """Normalize a block-score input to the 5-slot vector indexed by BLOCK_TYPES.

    Accepts a mapping keyed by 'plains'/'forest'/'peak'/'water' (case-insensitive; missing = 0),
    or an already-indexed sequence of length 5 (index 0 = sentinel).
    """
    if isinstance(blocks, dict):
        vec = [0, 0, 0, 0, 0]
        for k, v in blocks.items():
            idx = BLOCK_TYPES.get(str(k).lower())
            if idx is None:
                raise ValueError(f"unknown block type {k!r}; use {list(BLOCK_TYPES)[1:]}")
            vec[idx] = int(v)
        return vec
    vec = list(blocks)
    if len(vec) != 5:
        raise ValueError("indexed block vector must have length 5 (index 0 is the sentinel)")
    return [int(x) for x in vec]


def resolve_safari_slots(area: str, tod, blocks, method: str = "grass") -> list[tuple[str, int]]:
    """The 10 encounter slots (``(species, level)``) for an area/time-of-day/block config.

    ``blocks`` is the day-multiplier-applied score per type (see module docstring).  Mirrors
    PokeFinder ``getHGSSSafari``: each satisfied block-conditional replaces the next slot from the
    top, in conditional order; unsatisfied conditionals are skipped permanently.  Every method
    resolves to 10 slots, but how many conditionals compete for them differs (grass 10, surf 3,
    each rod 2).
    """
    method = normalize_method(method)
    table = _method_table(area, method)
    tod_name = _tod_name(tod)
    normal = table["normal"][tod_name]
    block = table["block"][tod_name]
    conds = table["conditions"]
    vec = _block_vector(blocks)

    out = []
    bi = 0
    for j in range(10):
        specie, level = normal[j]
        while bi < len(conds):
            t1, q1, t2, q2 = conds[bi]
            if vec[t1] >= q1 and vec[t2] >= q2:
                specie, level = block[bi]
                bi += 1
                break
            bi += 1
        out.append((specie, level))
    return out


def hook_rate(method: str, happiness_bonus: int = 0, suction_cups: bool = False) -> int:
    """A rod's chance out of 100 that something bites (the nibble check's threshold).

    ``rate = (base + happiness_bonus) * (2 if suction_cups else 1)``, per PokeFinder
    ``WildGenerator4::generateMethodK``.  May exceed 100, which simply means it always bites.
    Raises for a non-rod method -- grass and surf have no such check.
    """
    method = normalize_method(method)
    if method not in ROD_METHODS:
        raise ValueError(f"{METHOD_LABELS[method]} has no nibble check; rods: {list(ROD_METHODS)}")
    rate = ROD_BASE_RATE[method] + int(happiness_bonus)
    return rate * 2 if suction_cups else rate


def rod_hooks(seed: int, frame: int, method: str, happiness_bonus: int = 0,
              suction_cups: bool = False) -> bool:
    """Whether casting `method` on advance `frame` of `seed` hooks anything at all.

    False is "Not even a nibble..." -- no encounter, and the stream ends up exactly one advance
    further on (the check itself), so a failed cast is a cheap single advance.
    """
    rate = hook_rate(method, happiness_bonus, suction_cups)
    state = seed
    for _ in range(frame + 1):            # the nibble check is the encounter's first draw
        state = advance_rng(state)
    return (state >> 16) % 100 < rate


def frame_slot(seed: int, frame: int, method: str = "grass") -> int:
    """The encounter slot (0..9) for acting on advance ``frame`` of ``seed``.

    For a rod this is the slot that *would* be drawn; whether anything bites is a separate
    question (``rod_hooks``).
    """
    state = seed
    for _ in range(frame + _SLOT_DRAW[normalize_method(method)]):
        state = advance_rng(state)
    return (state >> 16) % 10


def advance_frame_species(seed: int, frame: int, area: str, tod, blocks, method: str = "grass",
                          happiness_bonus: int = 0,
                          suction_cups: bool = False) -> tuple[str, int] | None:
    """The ``(species, level)`` encountered when acting on ``frame`` of ``seed``.

    ``None`` only for a rod whose nibble check fails on that frame -- nothing bites, so there
    is no encounter to name.
    """
    method = normalize_method(method)
    if method in ROD_METHODS and not rod_hooks(seed, frame, method, happiness_bonus, suction_cups):
        return None
    return resolve_safari_slots(area, tod, blocks, method)[frame_slot(seed, frame, method)]


def iter_encounter_frames(seed: int, area: str, tod, blocks, target: str = "metang",
                          min_frame: int = 0, max_frame: int = 300, *, method: str = "grass",
                          happiness_bonus: int = 0, suction_cups: bool = False):
    """Yield ``(frame, level)`` for every advance frame in ``[min_frame, max_frame]`` whose
    encounter is ``target`` (ascending).  Empty if the target occupies no slot in this config.

    Lets a caller walk successive candidate frames -- e.g. to skip one whose Elm-call approach
    margin is ambiguous and take the next.  For a rod, frames whose nibble check fails are not
    candidates at all (nothing bites there, whatever the slot would have been).
    """
    method = normalize_method(method)
    slots = resolve_safari_slots(area, tod, blocks, method)
    target = canonical_species_name(target)
    hit_slots = {i for i, (sp, _lv) in enumerate(slots)
                 if canonical_species_name(sp) == target}
    if not hit_slots:
        return
    rod = method in ROD_METHODS
    rate = hook_rate(method, happiness_bonus, suction_cups) if rod else 0
    # Walk the RNG forward once rather than re-advancing from the seed for every frame.
    state = seed
    for _ in range(min_frame):
        state = advance_rng(state)
    for frame in range(min_frame, max_frame + 1):
        state = advance_rng(state)                # state is now advance_rng^(frame+1)(seed)
        if rod:
            if (state >> 16) % 100 >= rate:       # "Not even a nibble..." -- no encounter
                continue
            slot = (advance_rng(state) >> 16) % 10   # the slot draw is one further on
        else:
            slot = (state >> 16) % 10
        if slot in hit_slots:
            yield frame, slots[slot][1]


def find_encounter_frame(seed: int, area: str, tod, blocks, target: str = "metang",
                         min_frame: int = 0, max_frame: int = 300, *, method: str = "grass",
                         happiness_bonus: int = 0,
                         suction_cups: bool = False) -> tuple[int, int] | None:
    """Nearest advance frame in ``[min_frame, max_frame]`` whose encounter is ``target``.

    Returns ``(frame, level)`` or ``None`` if the target does not occupy any slot in this config
    (e.g. its block requirement is not met) or none is found in range.  Species match is by
    lower-cased name.
    """
    return next(iter_encounter_frames(seed, area, tod, blocks, target, min_frame, max_frame,
                                      method=method, happiness_bonus=happiness_bonus,
                                      suction_cups=suction_cups), None)


def _block_type_name(idx: int) -> str:
    for name, i in BLOCK_TYPES.items():
        if i == idx:
            return name
    raise ValueError(f"unknown block type index {idx!r}")


def _appears_in(area_key: str, method: str, target_l: str) -> bool:
    """Whether `target_l` occupies a slot in `area_key`/`method` under ANY time of day --
    unconditioned, or via a block-conditional whether or not that score is currently met."""
    entry = _zones()[area_key]
    if method not in entry:
        return False
    table = entry[method]
    for tod_name in _TOD:
        for kind in ("normal", "block"):
            if any(canonical_species_name(sp) == target_l
                   for sp, _ in table[kind][tod_name]):
                return True
    return False


def locations_for_species(target: str) -> list[dict]:
    """Every ``{"area", "method"}`` pair where `target` can appear at all -- unconditioned in
    some time of day's normal table, or reachable via a block-conditional slot (whether or not
    that block score is currently met).  Ordered by area, then by ``METHODS`` order.

    This is the "where do I even hunt this" answer now that a species may be reachable by
    several methods (Poliwhirl surfaces in Wetland surf, and on three different rods).
    """
    target_l = canonical_species_name(target)
    out = []
    for area in safari_areas():
        key = _area_key(area)
        for method in safari_methods(area):
            if _appears_in(key, method, target_l):
                out.append({"area": area, "method": method})
    return out


def areas_for_species(target: str, method: str | None = None) -> list[str]:
    """Every Safari-Zone area where `target` can appear at all — unconditioned in some
    time of day's normal table, or reachable via a block-conditional slot in some time of
    day (whether or not that block score is currently met). Canonical area-name spelling,
    in safari_areas()'s own order.

    `method=None` (the default) means *any* method — the areas worth considering at all.
    Pass a specific method to ask about just that one."""
    target_l = canonical_species_name(target)
    methods = METHODS if method is None else (normalize_method(method),)
    return [area for area in safari_areas()
            if any(_appears_in(_area_key(area), m, target_l) for m in methods)]


def methods_for_species(area: str, target: str) -> list[str]:
    """Which of `area`'s methods can yield `target` at all, in ``METHODS`` order."""
    target_l = canonical_species_name(target)
    key = _area_key(area)
    return [m for m in safari_methods(area) if _appears_in(key, m, target_l)]


def block_requirement_for(area: str, target: str, tod=None, method: str = "grass") -> dict | None:
    """The block score needed for `target` to become reachable via a block-conditional
    slot in `area` by `method`, or None if it's either unreachable that way at all, or
    already reachable without any block condition (appears in the area's own "normal" table
    for the checked time(s) of day — some areas carry a species unconditionally in one time of
    day and only conditionally in another; an unconditional route means no real
    requirement exists there).

    `tod=None` (the default) checks every time of day and returns the requirement with the
    LOWEST quantity — meeting the easiest condition's threshold is what a UI label showing
    "what do I need overall" wants. Pass a specific `tod` (as find_target_frame's own
    pre-flight check does) to get the requirement for exactly that time of day instead —
    the conditions LIST is shared across every time of day, but which species a given
    condition unlocks can differ per time of day, so the "easiest overall" answer isn't
    always the right one for one specific search.

    Returns {"block_type": "peak", "quantity": 56} (the same string key
    resolve_safari_slots's `blocks` dict accepts) using the game's real second-condition
    slot too when a condition actually has two non-sentinel requirements (none of this
    app's known target species do, but this doesn't assume that stays true forever):
    {"block_type": ..., "quantity": ..., "block_type_2": ..., "quantity_2": ...}.
    """
    table = _method_table(area, normalize_method(method))
    conds = table["conditions"]
    target_l = canonical_species_name(target)
    tods = [_tod_name(tod)] if tod is not None else list(_TOD)

    for tod_name in tods:
        if any(canonical_species_name(sp) == target_l
               for sp, _ in table["normal"][tod_name]):
            return None

    best = None
    for tod_name in tods:
        block = table["block"][tod_name]
        for i, (sp, _lvl) in enumerate(block):
            if canonical_species_name(sp) != target_l:
                continue
            t1, q1, t2, q2 = conds[i]
            req = {"block_type": _block_type_name(t1), "quantity": q1}
            if t2 != 0:
                req["block_type_2"] = _block_type_name(t2)
                req["quantity_2"] = q2
            if best is None or q1 < best["quantity"]:
                best = req
    return best
